-- =====================================================================
-- Consultor IA: conversas do usuário com o Claude e as mensagens de cada uma.
-- Apagar o usuário (inclusive pelo painel de admin) apaga as conversas, e apagar a
-- conversa apaga as mensagens (ON DELETE CASCADE).
-- =====================================================================

CREATE TABLE conversa (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT       NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    titulo         VARCHAR(60),                   -- NULL até a primeira pergunta (vira os 40 primeiros caracteres dela)
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Lista do usuário: WHERE usuario_id = ? ORDER BY atualizado_em DESC
CREATE INDEX idx_conversa_usuario_atualizado ON conversa (usuario_id, atualizado_em DESC);


CREATE TABLE mensagem (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversa_id     BIGINT       NOT NULL REFERENCES conversa (id) ON DELETE CASCADE,
    papel           VARCHAR(10)  NOT NULL,
    conteudo        TEXT         NOT NULL,
    tokens_entrada  INTEGER,                      -- só nas respostas (ASSISTANT): uso informado pela Anthropic
    tokens_saida    INTEGER,
    criado_em       TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_mensagem_papel CHECK (papel IN ('USER', 'ASSISTANT'))
);

-- Mensagens da conversa em ordem + o ON DELETE CASCADE da conversa
CREATE INDEX idx_mensagem_conversa ON mensagem (conversa_id, id);
-- Limite diário: perguntas (USER) do usuário desde 00:00
CREATE INDEX idx_mensagem_papel_criado ON mensagem (papel, criado_em);
