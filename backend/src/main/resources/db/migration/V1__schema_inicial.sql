-- =====================================================================
-- Nexum: schema inicial (PostgreSQL 16+)
-- Baseado no schema antigo (MySQL/Prisma), ver backend-legacy-api.md.
--
-- Regras:
--   - Dinheiro sempre NUMERIC(12,2): nunca float/double (arredonda errado).
--   - Datas com hora em TIMESTAMPTZ (guarda em UTC); datas só de dia em DATE.
--   - Toda tabela de dados do usuário tem usuario_id com ON DELETE CASCADE:
--     apagar o usuário apaga tudo dele.
--   - Este arquivo NUNCA deve ser editado depois de aplicado. Mudanças: V3__..., V4__...
-- =====================================================================


-- ---------------------------------------------------------------------
-- usuario
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    id_usuario     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(100) NOT NULL,
    email          VARCHAR(150) NOT NULL,          -- salvo sempre em minúsculas
    senha_hash     VARCHAR(255) NOT NULL,          -- BCrypt, nunca a senha pura
    telefone       VARCHAR(20),
    papel          VARCHAR(10)  NOT NULL DEFAULT 'USER',
    ativo          BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_papel CHECK (papel IN ('USER', 'ADMIN'))
);


-- ---------------------------------------------------------------------
-- categoria
-- usuario_id NULL = categoria padrão (global), visível para todos.
-- ---------------------------------------------------------------------
CREATE TABLE categoria (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT       REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    nome           VARCHAR(60)  NOT NULL,
    tipo           VARCHAR(10)  NOT NULL,
    icone          VARCHAR(50),
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_categoria_tipo CHECK (tipo IN ('receita', 'despesa')),
    -- NULLS NOT DISTINCT: também impede duas categorias globais com o mesmo nome e tipo.
    -- Este índice único já serve para buscas por usuario_id.
    CONSTRAINT uq_categoria_usuario_nome_tipo UNIQUE NULLS NOT DISTINCT (usuario_id, nome, tipo)
);


-- ---------------------------------------------------------------------
-- transacao
-- ---------------------------------------------------------------------
CREATE TABLE transacao (
    id_transacao   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT        NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    categoria_id   BIGINT        REFERENCES categoria (id) ON DELETE SET NULL,
    tipo           VARCHAR(10)   NOT NULL DEFAULT 'despesa',
    descricao      VARCHAR(255),
    valor          NUMERIC(12,2) NOT NULL,
    data           TIMESTAMPTZ   NOT NULL,
    conta          VARCHAR(30),                    -- "Conta principal", "Cartão de crédito"... (hoje o front guarda no navegador)
    criado_em      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT ck_transacao_tipo CHECK (tipo IN ('receita', 'despesa')),
    CONSTRAINT ck_transacao_valor CHECK (valor > 0)  -- o sinal vem do tipo, não do valor
);

-- Listagem do mês: WHERE usuario_id = ? AND data BETWEEN ? AND ? ORDER BY data
CREATE INDEX idx_transacao_usuario_data ON transacao (usuario_id, data);
-- Filtro por categoria e o ON DELETE SET NULL da categoria
CREATE INDEX idx_transacao_categoria ON transacao (categoria_id);


-- ---------------------------------------------------------------------
-- meta (antiga meta_financeira)
-- ---------------------------------------------------------------------
CREATE TABLE meta (
    id_meta        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT        NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    descricao      VARCHAR(255)  NOT NULL,
    valor_alvo     NUMERIC(12,2) NOT NULL,
    valor_atual    NUMERIC(12,2) NOT NULL DEFAULT 0,
    aporte_mensal  NUMERIC(12,2) NOT NULL DEFAULT 0,
    data_inicio    DATE          NOT NULL DEFAULT CURRENT_DATE,
    data_prazo     DATE          NOT NULL,
    status_meta    VARCHAR(20)   NOT NULL DEFAULT 'em_andamento',
    icone          VARCHAR(30),                    -- viagem, reserva, consumo... (hoje o front guarda no navegador)
    criado_em      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT ck_meta_valor_alvo CHECK (valor_alvo > 0),
    CONSTRAINT ck_meta_valor_atual CHECK (valor_atual >= 0),
    CONSTRAINT ck_meta_aporte CHECK (aporte_mensal >= 0),
    CONSTRAINT ck_meta_status CHECK (status_meta IN ('em_andamento', 'concluida', 'cancelada'))
);

-- Listagem: WHERE usuario_id = ? ORDER BY data_prazo
CREATE INDEX idx_meta_usuario_prazo ON meta (usuario_id, data_prazo);


-- ---------------------------------------------------------------------
-- orcamento: planejamento mensal por categoria
-- Uma linha = "em <mes_referencia>, posso gastar até <limite> em <categoria>".
-- mes_referencia é sempre o dia 1 do mês (ex.: 2026-11-01).
-- ---------------------------------------------------------------------
CREATE TABLE orcamento (
    id_orcamento   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT        NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    categoria_id   BIGINT        NOT NULL REFERENCES categoria (id) ON DELETE CASCADE,
    mes_referencia DATE          NOT NULL,
    limite         NUMERIC(12,2) NOT NULL,
    criado_em      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT ck_orcamento_limite CHECK (limite >= 0),
    CONSTRAINT ck_orcamento_mes CHECK (EXTRACT(DAY FROM mes_referencia) = 1),
    -- Um limite por categoria por mês. Também serve de índice para (usuario_id, mes_referencia).
    CONSTRAINT uq_orcamento_usuario_mes_categoria UNIQUE (usuario_id, mes_referencia, categoria_id)
);

-- ON DELETE CASCADE da categoria
CREATE INDEX idx_orcamento_categoria ON orcamento (categoria_id);
